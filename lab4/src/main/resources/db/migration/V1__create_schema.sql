-- Пользователи системы (кураторы выставок и др.)
CREATE TABLE users (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username   VARCHAR(50)              NOT NULL,
    full_name  VARCHAR(150)             NOT NULL,
    email      VARCHAR(254)             NOT NULL,
    version    BIGINT                   NOT NULL DEFAULT 0,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_users_username UNIQUE (username),
    CONSTRAINT uq_users_email UNIQUE (email),
    CONSTRAINT ck_users_username_lower CHECK (username = LOWER(username)),
    CONSTRAINT ck_users_email_lower CHECK (email = LOWER(email))
);

-- Экспонаты
CREATE TABLE exhibits (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          VARCHAR(200)             NOT NULL,
    condition     VARCHAR(30)              NOT NULL,
    required_area DOUBLE PRECISION         NOT NULL,
    version       BIGINT                   NOT NULL DEFAULT 0,
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT ck_exhibits_condition
        CHECK (condition IN ('EXCELLENT', 'GOOD', 'SATISFACTORY', 'NEEDS_RESTORATION')),
    CONSTRAINT ck_exhibits_required_area CHECK (required_area > 0)
);

-- Экспозиционные залы
CREATE TABLE exhibition_halls (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       VARCHAR(200)             NOT NULL,
    area       DOUBLE PRECISION         NOT NULL,
    available  BOOLEAN                  NOT NULL DEFAULT TRUE,
    version    BIGINT                   NOT NULL DEFAULT 0,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_exhibition_halls_name UNIQUE (name),
    CONSTRAINT ck_exhibition_halls_area CHECK (area > 0)
);

-- Выставки; куратор — пользователь (при удалении пользователя ссылка обнуляется)
CREATE TABLE exhibitions (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title      VARCHAR(200)             NOT NULL,
    start_date DATE                     NOT NULL,
    end_date   DATE                     NOT NULL,
    status     VARCHAR(20)              NOT NULL DEFAULT 'PLANNED',
    curator_id BIGINT,
    opened_at  TIMESTAMP WITH TIME ZONE,
    closed_at  TIMESTAMP WITH TIME ZONE,
    version    BIGINT                   NOT NULL DEFAULT 0,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_exhibitions_curator FOREIGN KEY (curator_id) REFERENCES users (id) ON DELETE SET NULL,
    CONSTRAINT ck_exhibitions_dates CHECK (end_date >= start_date),
    CONSTRAINT ck_exhibitions_status CHECK (status IN ('PLANNED', 'ACTIVE', 'COMPLETED', 'CANCELLED')),
    -- Открытая выставка всегда имеет дату открытия, завершённая — дату закрытия.
    CONSTRAINT ck_exhibitions_opened CHECK (status NOT IN ('ACTIVE', 'COMPLETED') OR opened_at IS NOT NULL),
    CONSTRAINT ck_exhibitions_closed CHECK (status <> 'COMPLETED' OR closed_at IS NOT NULL)
);

CREATE INDEX ix_exhibitions_curator ON exhibitions (curator_id);

-- Размещение экспоната на выставке в зале (связь многие-ко-многим с атрибутами)
CREATE TABLE exhibit_placements (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    exhibit_id      BIGINT                   NOT NULL,
    exhibition_id   BIGINT                   NOT NULL,
    hall_id         BIGINT                   NOT NULL,
    mounting_status VARCHAR(20)              NOT NULL DEFAULT 'PLANNED',
    mounted_at      TIMESTAMP WITH TIME ZONE,
    version         BIGINT                   NOT NULL DEFAULT 0,
    created_at      TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at      TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_placements_exhibit FOREIGN KEY (exhibit_id) REFERENCES exhibits (id) ON DELETE CASCADE,
    CONSTRAINT fk_placements_exhibition FOREIGN KEY (exhibition_id) REFERENCES exhibitions (id) ON DELETE CASCADE,
    CONSTRAINT fk_placements_hall FOREIGN KEY (hall_id) REFERENCES exhibition_halls (id) ON DELETE CASCADE,
    -- Один экспонат размещается на конкретной выставке не более одного раза.
    CONSTRAINT uq_placements_exhibit_exhibition UNIQUE (exhibit_id, exhibition_id),
    CONSTRAINT ck_placements_status
        CHECK (mounting_status IN ('PLANNED', 'IN_PROGRESS', 'MOUNTED', 'DISMANTLED')),
    CONSTRAINT ck_placements_mounted CHECK (mounting_status <> 'MOUNTED' OR mounted_at IS NOT NULL)
);

CREATE INDEX ix_placements_exhibition ON exhibit_placements (exhibition_id);
CREATE INDEX ix_placements_hall ON exhibit_placements (hall_id);
