package ru.rbpo.museum.model;

/** Отдельные права, из которых складываются роли. */
public enum Permission {
    /** Управление учётными записями и ролями. */
    USER_MANAGE,
    /** Создание, изменение и удаление залов. */
    HALL_MANAGE,
    /** Создание и изменение экспонатов, отправка на реставрацию. */
    EXHIBIT_MANAGE,
    /** Удаление экспонатов из фонда. */
    EXHIBIT_DELETE,
    /** Создание выставок (куратор становится их куратором). */
    EXHIBITION_CREATE,
    /** Управление любыми выставками и размещениями, независимо от куратора. */
    EXHIBITION_MANAGE_ANY
}
